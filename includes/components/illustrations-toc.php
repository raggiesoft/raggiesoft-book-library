 * ============================================================================
 * REUSABLE COMPONENT: Narrative Table of Illustrations (illustrations-toc.php)
 * ============================================================================
 * PURPOSE:
 * Renders a responsive, accessible (WCAG 2.1 AA / Section 508), theme-aware
 * Table of Contents for all narrative illustrations across any book or series
 * in Ocean View Archives (`books.raggiesoft.com`).
 *
 * REUSABILITY CONTRACT:
 * Can be included on:
 *   1. Dedicated `/<seriesSlug>/illustrations` page (`sophia/illustrations.php`)
 *   2. Master Table of Contents (`sophia/toc.php`) via collapsible gallery mode
 *   3. Any future narrative property or multi-book index.
 *
 * EXPECTED CONTEXT VARIABLES:
 * - `$toc_manifest` (array): Parsed `toc.json` manifest generated by `paige.php`.
 * - `$cdnBaseUrl`   (string): Base CDN URL (`https://assets.raggiesoft.com`).
 * - `$seriesSlug`   (string): Current narrative slug (e.g., `aubrie`, `rachel`).
 * - `$fileToUrl`    (array): Optional lookup mapping relative `.md` paths to URLs.
 * - `$illustrationsTocMode` (string): `'page'` (default) or `'embedded'`.
 *
 * MODERN WEB GUIDANCE ARCHITECTURE:
 * - `css-layout`:
 *   - Responsive CSS Grid (`repeat(auto-fill, minmax(min(100%, 280px), 1fr))`)
 *     with `grid-template-rows: auto 1fr auto` so card media headers, bodies,
 *     and action footers align cleanly across every row.
 *   - `aspect-ratio: 16 / 9; inline-size: 100%; block-size: auto; display: block;`
 *     on `<img>` thumbnails to prevent layout shift and baseline descender gaps.
 *   - `flex-wrap: wrap; flex-wrap: balance;` on the Era quick-jump pill bar.
 *   - `-webkit-line-clamp: 3; line-clamp: 3; overflow: clip;` on scene captions.
 *   - Native `<dialog>` element invoked via `.showModal()` for full-resolution
 *     artwork inspection with focus trapping and inert backdrop.
 * - `defer-rendering-heavy-content`:
 *   - Applies `content-visibility: auto; contain-intrinsic-size: auto none auto 420px;`
 *     strictly to below-the-fold Era sections (`$eraGalleryIndex > 0`).
 * ============================================================================
 */

if (!isset($illustrationsTocMode)) {
    $illustrationsTocMode = 'page';
}

$cdnBase = isset($cdnBaseUrl) ? rtrim($cdnBaseUrl, '/') : 'https://assets.raggiesoft.com';
$activeSeriesSlug = $seriesSlug ?? ($toc_manifest['series_slug'] ?? '');
$activeSeriesTitle = $toc_manifest['series_title'] ?? ucwords(str_replace('-', ' ', $activeSeriesSlug));

/**
 * Helper: Normalize an illustration source path into a full CDN or absolute URL.
 * Expands `{{CDN}}` / `{{cms}}` macros and strips `#fullwidth` display fragments.
 */
if (!function_exists('resolveNarrativeIllustrationUrl')) {
    function resolveNarrativeIllustrationUrl(string $rawSrc, string $cdnBase): string {
        $src = trim($rawSrc);
        if ($src === '') {
            return '';
        }
        // Strip Markdown layout fragments such as #fullwidth
        $src = (string)preg_replace('/#.*$/', '', $src);
        // Strip {{CDN}}, {{cms}}, or leading CDN origin so we can normalize relative paths
        $src = str_replace(['{{CDN}}', '{{cms}}', $cdnBase, 'https://assets.raggiesoft.com'], '', $src);
        if (preg_match('/^https?:\/\//i', $src)) {
            return $src;
        }
        $cleanRel = ltrim($src, '/');
        if ($cleanRel === '') {
            return '';
        }
        if (
            strpos($cleanRel, 'raggiesoft-books/') !== 0 &&
            strpos($cleanRel, 'raggiesoft-lore/') !== 0 &&
            strpos($cleanRel, 'engine-room-records/') !== 0
        ) {
            $cleanRel = 'raggiesoft-books/images/scenes/' . $cleanRel;
        }
        return $cdnBase . '/' . $cleanRel;
    }
}

// ============================================================================
// STEP 1: COLLECT ILLUSTRATED PARTS GROUPED BY ERA
// ============================================================================
$illustratedEras = [];
$totalIllustrationsCount = 0;
$totalIllustratedPartsCount = 0;
$globalIllustrationNumber = 0;

if (!empty($toc_manifest['eras']) && is_array($toc_manifest['eras'])) {
    foreach ($toc_manifest['eras'] as $eIdx => $era) {
        $eraNum = $era['era_num'] ?? ($eIdx + 1);
        $eraTitle = $era['era_title'] ?? "Era {$eraNum}";
        $eraUrl = !empty($era['era_url'])
            ? str_replace('/raggiesoft-books/books', '', $era['era_url'])
            : "/{$activeSeriesSlug}";

        $eraItems = [];

        if (!empty($era['chapters']) && is_array($era['chapters'])) {
            foreach ($era['chapters'] as $cIdx => $chap) {
                $chapNum = $chap['chap_num'] ?? ($cIdx + 1);
                $chapTitle = $chap['chap_title'] ?? "Chapter {$chapNum}";
                $chapUrl = !empty($chap['chap_url'])
                    ? str_replace('/raggiesoft-books/books', '', $chap['chap_url'])
                    : $eraUrl;

                if (!empty($chap['parts']) && is_array($chap['parts'])) {
                    foreach ($chap['parts'] as $part) {
                        $partImages = [];

                        if (!empty($part['images']) && is_array($part['images'])) {
                            $partImages = $part['images'];
                        } elseif (!empty($part['image'])) {
                            $partImages[] = [
                                'src' => $part['image'],
                                'alt' => $part['image_alt'] ?? ''
                            ];
                        }

                        if (empty($partImages)) {
                            continue;
                        }

                        // Deduplicate images within the same part after normalizing URLs
                        $normalizedPartImages = [];
                        $seenUrls = [];
                        foreach ($partImages as $imgMeta) {
                            $rawSrc = is_array($imgMeta) ? ($imgMeta['src'] ?? '') : (string)$imgMeta;
                            $rawAlt = is_array($imgMeta) ? ($imgMeta['alt'] ?? '') : '';
                            $fullImgUrl = resolveNarrativeIllustrationUrl($rawSrc, $cdnBase);
                            if ($fullImgUrl === '' || in_array($fullImgUrl, $seenUrls, true)) {
                                continue;
                            }
                            $seenUrls[] = $fullImgUrl;
                            $normalizedPartImages[] = [
                                'src' => $fullImgUrl,
                                'alt' => $rawAlt
                            ];
                        }

                        if (empty($normalizedPartImages)) {
                            continue;
                        }

                        $totalIllustratedPartsCount++;
                        $partFilePath = $part['file_path'] ?? '';
                        $partUrl = $part['url'] ?? ($fileToUrl[$partFilePath] ?? '#');
                        $partTitle = $part['part_title'] ?? 'Untitled Part';
                        $partDate = $part['date'] ?? '';
                        $partStartTime = $part['start_time'] ?? '';
                        $partLocation = $part['location'] ?? '';

                        foreach ($normalizedPartImages as $imgIdx => $normImg) {
                            $globalIllustrationNumber++;
                            $totalIllustrationsCount++;

                            $eraItems[] = [
                                'number'       => $globalIllustrationNumber,
                                'img_index'    => $imgIdx + 1,
                                'img_total'    => count($normalizedPartImages),
                                'src'          => $normImg['src'],
                                'alt'          => $normImg['alt'] !== '' ? $normImg['alt'] : "{$partTitle} ({$chapTitle})",
                                'caption'      => $normImg['alt'],
                                'part_title'   => $partTitle,
                                'part_url'     => $partUrl,
                                'chap_num'     => $chapNum,
                                'chap_title'   => $chapTitle,
                                'chap_url'     => $chapUrl,
                                'era_num'      => $eraNum,
                                'era_title'    => $eraTitle,
                                'era_url'      => $eraUrl,
                                'date'         => $partDate,
                                'start_time'   => $partStartTime,
                                'location'     => $partLocation
                            ];
                        }
                    }
                }
            }
        }

        if (!empty($eraItems)) {
            $illustratedEras[] = [
                'era_index'  => $eIdx,
                'era_num'    => $eraNum,
                'era_title'  => $eraTitle,
                'era_url'    => $eraUrl,
                'era_anchor' => 'illus-era-' . intval($eraNum),
                'items'      => $eraItems
            ];
        }
    }
}
