(function () {
    const searchInput = document.getElementById('lib-illus-search');
    const statusEl = document.getElementById('lib-illus-status');
    const filterButtons = Array.from(document.querySelectorAll('[data-book-filter]'));
    const sections = Array.from(document.querySelectorAll('.lib-illus-book-section'));
    let activeBook = 'all';

    function applyFilters() {
        const query = (searchInput ? searchInput.value : '').trim().toLowerCase();
        let visibleCount = 0;

        sections.forEach((sec) => {
            const slug = sec.getAttribute('data-book-slug');
            const bookMatches = (activeBook === 'all' || activeBook === slug);
            if (!bookMatches) {
                sec.style.display = 'none';
                return;
            }
            const cards = Array.from(sec.querySelectorAll('.lib-illus-card'));
            let sectionVisible = 0;
            cards.forEach((card) => {
                const hay = card.getAttribute('data-search') || '';
                const matches = (query === '' || hay.indexOf(query) !== -1);
                card.style.display = matches ? '' : 'none';
                if (matches) {
                    sectionVisible++;
                    visibleCount++;
                }
            });
            sec.style.display = sectionVisible > 0 ? '' : 'none';
        });

        if (statusEl) {
            statusEl.textContent = 'Showing ' + visibleCount.toLocaleString() + ' ' + (visibleCount === 1 ? 'illustration' : 'illustrations');
        }
    }

    filterButtons.forEach((btn) => {
        btn.addEventListener('click', () => {
            activeBook = btn.getAttribute('data-book-filter') || 'all';
            filterButtons.forEach((b) => b.setAttribute('aria-pressed', b === btn ? 'true' : 'false'));
            applyFilters();
        });
    });

    if (searchInput) {
        searchInput.addEventListener('input', applyFilters);
    }

    // Lightbox controller
    const dialog = document.getElementById('lib-illus-lightbox');
    const lbImg = document.getElementById('lib-illus-lb-img');
    const lbTitle = document.getElementById('lib-illus-lb-title');
    const lbKicker = document.getElementById('lib-illus-lb-kicker');
    const lbCaption = document.getElementById('lib-illus-lb-caption');
    const lbLink = document.getElementById('lib-illus-lb-link');
    const lbClose = document.getElementById('lib-illus-lb-close');

    document.addEventListener('click', (e) => {
        const trigger = e.target.closest('[data-lightbox-src]');
        if (!trigger || !dialog) return;
        e.preventDefault();
        lbImg.src = trigger.getAttribute('data-lightbox-src') || '';
        lbImg.alt = trigger.getAttribute('data-lightbox-alt') || '';
        lbTitle.textContent = trigger.getAttribute('data-lightbox-title') || '';
        lbKicker.textContent = trigger.getAttribute('data-lightbox-kicker') || '';
        lbCaption.textContent = trigger.getAttribute('data-lightbox-alt') || '';
        lbLink.href = trigger.getAttribute('data-lightbox-url') || '#';
        if (typeof dialog.showModal === 'function') {
            dialog.showModal();
        }
    });

    if (lbClose && dialog) {
        lbClose.addEventListener('click', () => dialog.close());
        dialog.addEventListener('click', (e) => {
            if (e.target === dialog) dialog.close();
        });
    }
})();
</script>

