/**
 * =============================================================================
 * Architecture & Maintenance Guide: sophia/all-illustrations.php
 * =============================================================================
 * Purpose:
 *     Library-Wide Table of Illustrations (/illustrations) for Ocean View Archives
 *     (https://books.raggiesoft.com/illustrations). Aggregates every full-bleed
 *     16:9 chapter plate and inline archival illustration across all illustrated
 *     novels in the Ocean View Archives catalog into a single searchable,
 *     filterable visual index with native <dialog> lightbox inspection.
 *
 * Design Principles:
 *     - Zero-Database Static Aggregation: Reads `catalog.json` and each
 *       illustrated series' `toc.json` generated by Paige (`paige.php`).
 *     - Instant Book Filtering & Search: Allows readers to filter by a single
 *       novel (e.g., The Rachel Narrative, The Eleventh Child, The Stardust Engine)
 *       or search across all 250+ scene titles, dates, locations, and captions.
 *     - Exact Jump Navigation: Avoids `content-visibility: auto` scroll-shortfall
 *       by unlocking target sections and using `data-no-spa="true"` on jump pills.
 *     - WCAG 2.1 AA Compliance: Enforces >= 4.5:1 text contrast across Light,
 *       Dark, and Sepia themes with full keyboard and screen-reader operability.
 * =============================================================================
 */

global $cdnBaseUrl, $siteName, $requestUri;

$resolvedCdn = !empty($cdnBaseUrl) ? rtrim($cdnBaseUrl, '/') : 'https://assets.raggiesoft.com';
$localBooksRoot = dirname(__DIR__, 4) . '/raggiesoft-assets/raggiesoft-books/books';

// Load master catalog
$localCatalogFile = $localBooksRoot . '/catalog.json';
$catalogJson = is_file($localCatalogFile)
    ? @file_get_contents($localCatalogFile)
    : @file_get_contents($resolvedCdn . '/raggiesoft-books/books/catalog.json');
$catalogEntries = $catalogJson ? (json_decode($catalogJson, true) ?: []) : [];

// Prioritize flagship novels first, followed by remaining illustrated volumes
$priorityOrder = [
    'rachel' => 1,
    'aubrie' => 2,
    'stardust-engine' => 3,
    'ad-astra' => 4,
    'crimson-node' => 5,
    'quantum-directive-3-casey' => 6,
    'luna-leo' => 7
];

usort($catalogEntries, function ($a, $b) use ($priorityOrder) {
    $slugA = $a['slug'] ?? '';
    $slugB = $b['slug'] ?? '';
    $pA = $priorityOrder[$slugA] ?? 99;
    $pB = $priorityOrder[$slugB] ?? 99;
    if ($pA !== $pB) return $pA <=> $pB;
    return ($b['illustration_count'] ?? 0) <=> ($a['illustration_count'] ?? 0);
});

$illustratedBooks = [];
$totalLibraryIllustrations = 0;

foreach ($catalogEntries as $catEntry) {
    if (!empty($catEntry['hide'])) continue;
    $bSlug = $catEntry['slug'] ?? '';
    $bCount = intval($catEntry['illustration_count'] ?? 0);
    if ($bSlug === '' || $bCount <= 0) continue;

    $localTocFile = $localBooksRoot . '/' . $bSlug . '/toc.json';
    $tocRaw = is_file($localTocFile)
        ? @file_get_contents($localTocFile)
        : @file_get_contents($resolvedCdn . '/raggiesoft-books/books/' . $bSlug . '/toc.json');
    if (!$tocRaw) continue;
    $tocData = json_decode($tocRaw, true);
    if (empty($tocData['eras']) || !is_array($tocData['eras'])) continue;

    $bookPlates = [];
    foreach ($tocData['eras'] as $era) {
        $eraNum = intval($era['era_num'] ?? 0);
        $eraTitle = $era['era_title'] ?? "Era {$eraNum}";
        foreach (($era['chapters'] ?? []) as $chap) {
            $chapNum = intval($chap['chap_num'] ?? 0);
            $chapTitle = $chap['chap_title'] ?? "Chapter {$chapNum}";
            foreach (($chap['parts'] ?? []) as $part) {
                $partImages = [];
                if (!empty($part['images']) && is_array($part['images'])) {
                    $partImages = $part['images'];
                } elseif (!empty($part['image'])) {
                    $partImages = [[
                        'src' => $part['image'],
                        'alt' => $part['image_alt'] ?? ''
                    ]];
                }
                if (empty($partImages)) continue;

                $partTitle = $part['part_title'] ?? 'Scene';
                $partUrl = $part['url'] ?? ('/' . $bSlug);
                $timeBadge = !empty($part['date'])
                    ? $part['date']
                    : (!empty($part['stardate']) ? 'Stardate ' . $part['stardate'] : (!empty($part['realm_time']) ? $part['realm_time'] : ''));
                $locBadge = $part['location'] ?? '';

                foreach ($partImages as $imgIdx => $imgObj) {
                    $rawSrc = $imgObj['src'] ?? '';
                    if ($rawSrc === '') continue;
                    $fullSrc = (strpos($rawSrc, 'http') === 0)
                        ? $rawSrc
                        : $resolvedCdn . '/' . ltrim($rawSrc, '/');
                    $altText = trim($imgObj['alt'] ?? '');
                    if ($altText === '') {
                        $altText = $partTitle . ' — ' . ($tocData['series_title'] ?? $bSlug);
                    }
                    $bookPlates[] = [
                        'src' => $fullSrc,
                        'alt' => $altText,
                        'part_title' => $partTitle,
                        'part_url' => $partUrl,
                        'era_title' => $eraTitle,
                        'chap_title' => $chapTitle,
                        'time' => $timeBadge,
                        'location' => $locBadge,
                        'plate_index' => $imgIdx + 1,
                        'plate_total' => count($partImages)
                    ];
                }
            }
        }
    }

    if (!empty($bookPlates)) {
        $plateCount = count($bookPlates);
        $totalLibraryIllustrations += $plateCount;
        $illustratedBooks[] = [
            'slug' => $bSlug,
            'title' => $tocData['series_title'] ?? ($catEntry['title'] ?? $bSlug),
            'short_description' => $tocData['series_short_description'] ?? ($catEntry['short_description'] ?? ''),
            'count' => $plateCount,
            'plates' => $bookPlates
        ];
    }
}
